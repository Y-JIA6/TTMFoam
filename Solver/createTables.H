// ===========================================================================
//  createTables.H
//  Builds the free-electron-gas lookup tables once at start-up: mu(Te),
//  Ce(Te), and G(Te). The solver then interpolates them in every cell rather
//  than re-evaluating the Fermi--Dirac integrals at every time step.
//
//  The Fermi energy is read from ttmProperties. The effective lookup range
//  used by TTmAl.C is 300 K <= Te <= T_max - dT - 1 K. FEG_param.dat is
//  written on the master rank for independent property-curve verification.
// ===========================================================================

Info<< "\n>> Generation des tables FEG : mu(Te), Ce(Te), G(Te)" << endl;

// ---------------------------------------------------------------------------
// 1. Temperature grid
// ---------------------------------------------------------------------------
const scalar T_max = 3.0e5;                 // Maximum tabulated temperature in K.
const scalar dT    = 10.0;                  // Temperature increment in K.
const label  num_entries = label(T_max/dT) + 10;

// ---------------------------------------------------------------------------
// 2. FEG parameters and reference coupling value
// ---------------------------------------------------------------------------
const scalar EF_val = mu.value();           // Fermi energy in J.

const scalar G_ref_val = G.value();         // Coupling factor in W/m3/K.

// ---------------------------------------------------------------------------
// 3. Table allocation and coupling normalization
// ---------------------------------------------------------------------------
List<scalar> mu_table(num_entries, 0.0);
List<scalar> Ce_table(num_entries, 0.0);
List<scalar> G_table (num_entries, 0.0);

const scalar mu_ref  = calculateMu(300.0, EF_val, gamma_val);
const scalar I_G_ref = calculateIntegralG(300.0, EF_val, gamma_val, mu_ref);

// ---------------------------------------------------------------------------
// 4. Fill Fermi--Dirac property tables
// ---------------------------------------------------------------------------
for (label i = 0; i < num_entries; ++i)
{
    const scalar Te = max(scalar(1.0), i*dT);

    const scalar mu = calculateMu(Te, EF_val, gamma_val);
    mu_table[i] = mu;
    Ce_table[i] = calculateCe(Te, EF_val, gamma_val, mu);
    G_table[i]  = G_ref_val*calculateIntegralG(Te, EF_val, gamma_val, mu)/I_G_ref;

    if (i % 2000 == 0)
    {
        Info<< "  -- Te = " << Te << " K :"
            << "  Ce = " << Ce_table[i]
            << "  G = "  << G_table[i] << endl;
    }
}

Info<< ">> Tables FEG generees (" << num_entries
    << " entrees, pas " << dT << " K)." << endl;

// ---------------------------------------------------------------------------
// 5. Export property curves for independent verification
// ---------------------------------------------------------------------------
if (Pstream::master())
{
    const scalar Tl_ref = T0.value();          // Reference lattice temperature in K.

    OFstream propFile("FEG_param.dat");
    propFile << "# Free-electron-gas property tables generated by createTables.H" << nl
             << "# EF = " << EF_val/1.602176634e-19 << " eV,  gamma = " << gamma_val
             << " J/m3/K2,  Tl_ref = " << Tl_ref << " K" << nl
             << "# 1:Te(K)  2:Ce(J/m3.K)  3:G(W/m3.K)  4:mu(eV)"
             << "  5:ke(W/m.K)  6:tau_e(s)" << nl;

    const label first_export_index = label(300.0/dT);
    for (label i = first_export_index; i < num_entries; i += 10)
    {
        const scalar Te    = max(scalar(1.0), i*dT);
        const scalar tau_e = calculateTauE(Te, Tl_ref, Ae_val, Bl_val);
        const scalar ke_Te = calculateKe(tau_e, Ce_table[i], vF_val);

        propFile << Te << "  " << Ce_table[i] << "  " << G_table[i]
                 << "  " << mu_table[i]/1.602176634e-19
                 << "  " << ke_Te << "  " << tau_e << nl;
    }
}

Info<< ">> Generation terminee en " << runTime.elapsedCpuTime() << " s\n" << endl;
